// Pure helpers of selector mode (files.js is a QML JS library; evaluated here without the pragma).
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8').replace('.pragma library', '');
const F = new Function(src + ';return {globToRegExp,matchesRule,matchesFilter,pickerCanSelect,pickerResolve,pickerAcceptLabel,validFileName,pickerSummary,pickerMaxSelection};')();
let bad = 0;
const t = (got, want, what) => { if (JSON.stringify(got) !== JSON.stringify(want)) { console.log('FAIL', what, JSON.stringify(got), '≠', JSON.stringify(want)); bad = 1; } };
const g = (glob, name) => F.globToRegExp(glob).test(name);
t(g('*.png', 'a.png'), true, 'glob suffix');
t(g('*.png', 'a.PNG'), false, 'globs are case sensitive');
t(g('*.[pP][nN][gG]', 'a.PNG'), true, 'bracket classes');
t(g('a?c', 'abc'), true, '?');
t(g('a?c', 'ac'), false, '? needs one char');
t(g('a.c', 'abc'), false, 'dot is literal');
t(g('*', 'x\ny'), true, '* matches newlines');
t(g('[!a]x', 'bx'), true, 'negated class');
t(g('[!a]x', 'ax'), false, 'negated class excludes');
t(g('a[', 'a['), true, 'unclosed bracket is literal');
t(g('(x)+$^', '(x)+$^'), true, 'regex metacharacters are literal');
t(g('a-b/*', 'a-b/c'), true, 'dash and slash');
const rule = (type, value) => ({ type, value });
t(F.matchesRule({ name: 'x', mime: 'image/png' }, rule('mime', 'image/*')), true, 'mime wildcard');
t(F.matchesRule({ name: 'x', mime: 'IMAGE/PNG' }, rule('mime', 'image/png')), true, 'mime case-insensitive');
t(F.matchesRule({ name: 'x', mime: 'imagex/png' }, rule('mime', 'image/*')), false, 'mime wildcard needs the slash');
t(F.matchesRule({ name: 'x', mime: null }, rule('mime', 'image/*')), false, 'no mime, no match');
const dir = { name: 'd', kind: 'dir' }, file = { name: 'a.txt', kind: 'file', mime: 'text/plain' };
t(F.matchesFilter(dir, { patterns: [rule('glob', '*.x')] }), true, 'folders always pass a filter');
t(F.matchesFilter(file, { patterns: [rule('glob', '*.x')] }), false, 'file outside the filter');
t(F.matchesFilter(file, { patterns: [] }), true, 'empty filter lets everything through');
t(F.matchesFilter(file, null), true, 'no filter');
const open = { kind: 'open', multiple: false, directory: false }, folder = { kind: 'open', directory: true, multiple: false };
t([F.pickerCanSelect(open, file), F.pickerCanSelect(open, dir)], [true, false], 'open: files only');
t([F.pickerCanSelect(folder, file), F.pickerCanSelect(folder, dir)], [false, true], 'folder: folders only');
t([F.pickerCanSelect({ kind: 'save_files' }, file), F.pickerCanSelect({ kind: 'save_files' }, dir)], [false, true], 'save_files: folders only');
t([F.pickerCanSelect({ kind: 'save' }, file), F.pickerCanSelect({ kind: 'save' }, dir)], [true, false], 'save: existing files fill the name');
t([F.pickerMaxSelection(open), F.pickerMaxSelection({ kind: 'open', multiple: true })], [1, 1e9], 'selection limits');
t(['..', '.', '', '  ', 'a/b', 'a\0b', 'x'.repeat(256), 'ok.txt', '-rf\nx'].map(F.validFileName), [false, false, false, false, false, false, false, true, true], 'file names');
t(F.pickerResolve({ kind: 'save' }, '/h/d', [], 'n.txt'), { ok: true, paths: ['/h/d/n.txt'], why: '' }, 'save resolve');
t(F.pickerResolve({ kind: 'save' }, '/h/d', [], 'a/b').ok, false, 'save refuses slash');
t(F.pickerResolve({ kind: 'save_files' }, 'trash:///', [], '').ok, false, 'save_files refuses the trash');
t(F.pickerResolve(folder, '/h/d', [], '').paths, ['/h/d'], 'folder: none selected = this folder');
t(F.pickerResolve(folder, 'net:///', [], '').ok, false, 'folder: not in net://');
t(F.pickerResolve(open, '/h/d', [], '').ok, false, 'open: nothing selected');
t(F.pickerResolve({ kind: 'open', multiple: true }, '/', [file], '').paths, ['/a.txt'], 'root folder join');
t([F.pickerAcceptLabel(open), F.pickerAcceptLabel(folder), F.pickerAcceptLabel({ kind: 'save' }), F.pickerAcceptLabel({ kind: 'save', accept_label: 'Exportar' })],
  ['Abrir', 'Elegir', 'Guardar', 'Exportar'], 'labels');
process.exit(bad);
